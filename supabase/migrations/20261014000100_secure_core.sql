-- A new auth identity always receives the least-privileged role. Metadata such
-- as raw_user_meta_data.role is deliberately ignored.
CREATE FUNCTION public.create_profile_for_auth_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
BEGIN
  IF NEW.email IS NULL OR btrim(NEW.email) = '' THEN
    RAISE EXCEPTION 'An email address is required to create a customer profile';
  END IF;
  INSERT INTO public.profiles(id, full_name, email, phone, role)
  VALUES (
    NEW.id,
    COALESCE(NULLIF(btrim(NEW.raw_user_meta_data ->> 'full_name'), ''), split_part(NEW.email, '@', 1)),
    NEW.email,
    COALESCE(NULLIF(btrim(NEW.raw_user_meta_data ->> 'phone'), ''), ''),
    'customer'
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;
CREATE TRIGGER create_profile_after_auth_signup
  AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.create_profile_for_auth_user();

-- These helpers only inspect the caller's own role. There is no arbitrary
-- user-id role lookup exposed to browser clients.
CREATE FUNCTION public.current_user_role()
RETURNS public.user_role LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog AS $$
  SELECT p.role FROM public.profiles AS p WHERE p.id = auth.uid()
$$;
CREATE FUNCTION public.is_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog AS $$
  SELECT COALESCE(public.current_user_role() = 'admin', false)
$$;
CREATE FUNCTION public.is_staff()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog AS $$
  SELECT COALESCE(public.current_user_role() IN ('staff', 'admin'), false)
$$;
CREATE FUNCTION public.is_assigned_staff(p_staff_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog AS $$
  SELECT EXISTS (SELECT 1 FROM public.staff s WHERE s.id = p_staff_id AND s.profile_id = auth.uid())
$$;

CREATE FUNCTION public.prevent_profile_role_escalation()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF NEW.id IS DISTINCT FROM OLD.id THEN
    RAISE EXCEPTION 'Profile identifiers cannot be changed';
  END IF;
  IF NEW.role IS DISTINCT FROM OLD.role
     AND NOT public.is_admin()
     AND current_user NOT IN ('postgres', 'supabase_admin') THEN
    RAISE EXCEPTION 'Only an administrator can change profile roles';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER prevent_profile_role_escalation_trigger
  BEFORE UPDATE ON public.profiles FOR EACH ROW EXECUTE FUNCTION public.prevent_profile_role_escalation();

-- Automatic, minimal audit records. No client can insert arbitrary audit rows.
CREATE FUNCTION public.audit_row_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE
  v_row jsonb;
  v_old jsonb;
  v_changed_fields text[];
  v_id text;
  v_name text;
  v_role public.user_role;
BEGIN
  IF auth.uid() IS NULL THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN v_row := to_jsonb(OLD); ELSE v_row := to_jsonb(NEW); END IF;
  IF TG_TABLE_NAME = 'staff_services' THEN
    v_id := (v_row ->> 'staff_id') || ':' || (v_row ->> 'service_id');
  ELSE
    v_id := COALESCE(v_row ->> 'id', v_row ->> 'staff_id', v_row ->> 'day_of_week', 'unknown');
  END IF;
  IF TG_OP = 'UPDATE' THEN
    v_old := to_jsonb(OLD);
    SELECT COALESCE(array_agg(fields.key ORDER BY fields.key), ARRAY[]::text[]) INTO v_changed_fields
      FROM jsonb_each(v_row) AS fields(key, value)
      WHERE fields.value IS DISTINCT FROM v_old -> fields.key;
  ELSE
    SELECT COALESCE(array_agg(fields.key ORDER BY fields.key), ARRAY[]::text[]) INTO v_changed_fields
      FROM jsonb_object_keys(v_row) AS fields(key);
  END IF;
  SELECT p.full_name, p.role INTO v_name, v_role FROM public.profiles p WHERE p.id = auth.uid();
  IF v_role IS NULL THEN RAISE EXCEPTION 'A profile is required to create an audit record'; END IF;
  INSERT INTO public.audit_logs(user_id, user_name, user_role, action, entity_type, entity_id, details)
  VALUES (auth.uid(), COALESCE(v_name, ''), v_role, TG_OP || '_' || upper(TG_TABLE_NAME), TG_TABLE_NAME, v_id,
          jsonb_build_object('operation', TG_OP, 'changed_fields', v_changed_fields));
  IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;
CREATE TRIGGER audit_services AFTER INSERT OR UPDATE OR DELETE ON public.services FOR EACH ROW EXECUTE FUNCTION public.audit_row_change();
CREATE TRIGGER audit_staff AFTER INSERT OR UPDATE OR DELETE ON public.staff FOR EACH ROW EXECUTE FUNCTION public.audit_row_change();
CREATE TRIGGER audit_staff_private AFTER INSERT OR UPDATE OR DELETE ON public.staff_private FOR EACH ROW EXECUTE FUNCTION public.audit_row_change();
CREATE TRIGGER audit_staff_services AFTER INSERT OR UPDATE OR DELETE ON public.staff_services FOR EACH ROW EXECUTE FUNCTION public.audit_row_change();
CREATE TRIGGER audit_hours AFTER INSERT OR UPDATE OR DELETE ON public.salon_business_hours FOR EACH ROW EXECUTE FUNCTION public.audit_row_change();
CREATE TRIGGER audit_holidays AFTER INSERT OR UPDATE OR DELETE ON public.salon_holidays FOR EACH ROW EXECUTE FUNCTION public.audit_row_change();
CREATE TRIGGER audit_appointments AFTER INSERT OR UPDATE OR DELETE ON public.appointments FOR EACH ROW EXECUTE FUNCTION public.audit_row_change();
CREATE TRIGGER audit_payments AFTER INSERT OR UPDATE OR DELETE ON public.payments FOR EACH ROW EXECUTE FUNCTION public.audit_row_change();

CREATE FUNCTION public.admin_set_profile_role(p_user_id uuid, p_role public.user_role)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_actor_name text; v_old_role public.user_role;
BEGIN
  IF public.is_admin() IS DISTINCT FROM true THEN RAISE EXCEPTION 'Administrator role required'; END IF;
  SELECT p.full_name INTO v_actor_name FROM public.profiles p WHERE p.id = auth.uid();
  SELECT p.role INTO v_old_role FROM public.profiles p WHERE p.id = p_user_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Profile not found'; END IF;
  UPDATE public.profiles SET role = p_role, updated_at = now() WHERE id = p_user_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Profile not found'; END IF;
  INSERT INTO public.audit_logs(user_id, user_name, user_role, action, entity_type, entity_id, details)
  VALUES (auth.uid(), COALESCE(v_actor_name, ''), 'admin', 'UPDATE_PROFILE_ROLE', 'profile', p_user_id::text,
          jsonb_build_object('old_role', v_old_role, 'new_role', p_role));
END;
$$;

-- Internal slot validator: use authoritative database services, hours, holidays
-- and staff schedules; a browser supplied price/duration is never trusted.
CREATE FUNCTION public.validate_booking_slot(
  p_date date, p_start time, p_duration integer, p_staff_id uuid,
  p_service_ids uuid[] DEFAULT NULL, p_exclude_appointment uuid DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE
  v_end time;
  v_hours public.salon_business_hours%ROWTYPE;
  v_staff_id uuid;
BEGIN
  IF p_duration < 1 OR p_duration > 600 THEN RAISE EXCEPTION 'Invalid service duration'; END IF;
  IF p_service_ids IS NOT NULL THEN
    IF cardinality(p_service_ids) = 0 THEN RAISE EXCEPTION 'At least one service is required'; END IF;
    PERFORM ss.staff_id FROM public.staff_services ss
      WHERE ss.service_id = ANY(p_service_ids) ORDER BY ss.staff_id, ss.service_id FOR SHARE;
  END IF;
  v_end := p_start + make_interval(mins => p_duration);
  IF v_end <= p_start THEN RAISE EXCEPTION 'Appointment cannot cross midnight'; END IF;
  IF p_date < (now() AT TIME ZONE 'Asia/Kolkata')::date
     OR (p_date + p_start) <= ((now() AT TIME ZONE 'Asia/Kolkata') + interval '15 minutes') THEN
    RAISE EXCEPTION 'Choose a future time at least 15 minutes from now';
  END IF;
  IF EXISTS (SELECT 1 FROM public.salon_holidays h WHERE h.holiday_date = p_date) THEN
    RAISE EXCEPTION 'The salon is closed on the selected date';
  END IF;
  SELECT * INTO v_hours FROM public.salon_business_hours h
   WHERE h.day_of_week = EXTRACT(DOW FROM p_date)::integer;
  IF NOT FOUND OR NOT v_hours.is_open OR p_start < v_hours.open_time OR v_end > v_hours.close_time THEN
    RAISE EXCEPTION 'The selected time is outside salon business hours';
  END IF;

  IF p_staff_id IS NOT NULL THEN
    SELECT s.id INTO v_staff_id FROM public.staff s
     WHERE s.id = p_staff_id AND s.is_active
       AND (p_service_ids IS NULL OR NOT EXISTS (
         SELECT 1 FROM unnest(p_service_ids) AS requested(service_id)
         WHERE NOT EXISTS (SELECT 1 FROM public.staff_services ss
                           WHERE ss.staff_id = s.id AND ss.service_id = requested.service_id)
       ))
       AND EXTRACT(DOW FROM p_date)::integer = ANY(s.working_days)
       AND p_start >= s.start_time AND v_end <= s.end_time
       AND NOT EXISTS (
         SELECT 1 FROM public.appointments a WHERE a.staff_id = s.id
           AND a.appointment_date = p_date AND a.id IS DISTINCT FROM p_exclude_appointment
           AND a.status NOT IN ('cancelled', 'no_show')
           AND p_start < a.end_time AND v_end > a.start_time
       );
  ELSE
    SELECT s.id INTO v_staff_id FROM public.staff s
     WHERE s.is_active AND EXTRACT(DOW FROM p_date)::integer = ANY(s.working_days)
       AND (p_service_ids IS NULL OR NOT EXISTS (
         SELECT 1 FROM unnest(p_service_ids) AS requested(service_id)
         WHERE NOT EXISTS (SELECT 1 FROM public.staff_services ss
                           WHERE ss.staff_id = s.id AND ss.service_id = requested.service_id)
       ))
       AND p_start >= s.start_time AND v_end <= s.end_time
       AND NOT EXISTS (
         SELECT 1 FROM public.appointments a WHERE a.staff_id = s.id
           AND a.appointment_date = p_date AND a.id IS DISTINCT FROM p_exclude_appointment
           AND a.status NOT IN ('cancelled', 'no_show')
           AND p_start < a.end_time AND v_end > a.start_time
       )
     ORDER BY s.id LIMIT 1;
  END IF;
  IF v_staff_id IS NULL THEN RAISE EXCEPTION 'That time is no longer available'; END IF;
  RETURN v_staff_id;
END;
$$;

CREATE FUNCTION public.get_available_slots(p_date date, p_duration_minutes integer, p_staff_id uuid DEFAULT NULL,
                                            p_service_ids uuid[] DEFAULT NULL)
RETURNS TABLE(available_time time) LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE
  v_hours public.salon_business_hours%ROWTYPE;
  v_slot time;
  v_end time;
BEGIN
  IF p_duration_minutes < 1 OR p_duration_minutes > 600 OR p_date IS NULL THEN
    RAISE EXCEPTION 'Invalid date or duration';
  END IF;
  IF p_date < (now() AT TIME ZONE 'Asia/Kolkata')::date
     OR EXISTS (SELECT 1 FROM public.salon_holidays h WHERE h.holiday_date = p_date) THEN RETURN; END IF;
  SELECT * INTO v_hours FROM public.salon_business_hours h
   WHERE h.day_of_week = EXTRACT(DOW FROM p_date)::integer AND h.is_open;
  IF NOT FOUND THEN RETURN; END IF;
  v_slot := v_hours.open_time;
  WHILE v_slot + make_interval(mins => p_duration_minutes) <= v_hours.close_time LOOP
    v_end := v_slot + make_interval(mins => p_duration_minutes);
    IF (p_date + v_slot) > ((now() AT TIME ZONE 'Asia/Kolkata') + interval '15 minutes')
       AND EXISTS (
         SELECT 1 FROM public.staff s WHERE s.is_active
            AND (p_staff_id IS NULL OR s.id = p_staff_id)
            AND (p_service_ids IS NULL OR NOT EXISTS (
              SELECT 1 FROM unnest(p_service_ids) AS requested(service_id)
              WHERE NOT EXISTS (SELECT 1 FROM public.staff_services ss
                                WHERE ss.staff_id = s.id AND ss.service_id = requested.service_id)
            ))
           AND EXTRACT(DOW FROM p_date)::integer = ANY(s.working_days)
           AND v_slot >= s.start_time AND v_end <= s.end_time
           AND NOT EXISTS (
             SELECT 1 FROM public.appointments a WHERE a.staff_id = s.id
               AND a.appointment_date = p_date AND a.status NOT IN ('cancelled', 'no_show')
               AND v_slot < a.end_time AND v_end > a.start_time
           )
       ) THEN available_time := v_slot; RETURN NEXT; END IF;
    v_slot := v_slot + interval '30 minutes';
  END LOOP;
END;
$$;

CREATE FUNCTION public.create_booking(
  p_service_ids uuid[], p_appointment_date date, p_start_time time,
  p_staff_id uuid DEFAULT NULL, p_customer_name text DEFAULT NULL,
  p_customer_phone text DEFAULT NULL, p_customer_email text DEFAULT NULL, p_notes text DEFAULT NULL
) RETURNS public.appointments LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE
  v_role public.user_role;
  v_service_count integer;
  v_price numeric(10,2);
  v_duration integer;
  v_snapshot_count integer;
  v_staff_id uuid;
  v_appointment public.appointments%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Sign in to book an appointment'; END IF;
  v_role := public.current_user_role();
  IF v_role IS DISTINCT FROM 'customer' THEN RAISE EXCEPTION 'A customer account is required to book'; END IF;
  IF p_service_ids IS NULL OR cardinality(p_service_ids) = 0
     OR cardinality(p_service_ids) <> (
       SELECT count(DISTINCT requested.service_id)
       FROM unnest(p_service_ids) AS requested(service_id)
     ) THEN
    RAISE EXCEPTION 'Select one or more distinct services';
  END IF;
  IF NULLIF(btrim(p_customer_name), '') IS NULL OR NULLIF(btrim(p_customer_phone), '') IS NULL
     OR position('@' IN COALESCE(p_customer_email, '')) < 2 THEN
    RAISE EXCEPTION 'Valid customer contact details are required';
  END IF;
  IF length(COALESCE(p_notes, '')) > 1000 THEN RAISE EXCEPTION 'Notes are too long'; END IF;
  -- Hold a stable catalogue snapshot until appointment service lines are written.
  -- ORDER BY gives concurrent bookings/admin edits a consistent lock order.
  PERFORM s.id FROM public.services s
   WHERE s.id = ANY(p_service_ids) ORDER BY s.id FOR SHARE;
  SELECT count(*), COALESCE(sum(s.price), 0), COALESCE(sum(s.duration_minutes), 0)
    INTO v_service_count, v_price, v_duration
    FROM public.services s WHERE s.id = ANY(p_service_ids) AND s.is_active
      AND s.price_confirmed AND NOT s.requires_confirmation;
  IF v_service_count <> cardinality(p_service_ids) THEN
    RAISE EXCEPTION 'A selected service is unavailable or requires salon price confirmation';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('oasis-booking-day:' || p_appointment_date::text, 0));
  v_staff_id := public.validate_booking_slot(p_appointment_date, p_start_time, v_duration, p_staff_id, p_service_ids);
  INSERT INTO public.appointments(
    booking_reference, customer_id, customer_name, customer_phone, customer_email, staff_id,
    appointment_date, start_time, end_time, total_duration_minutes, total_price, status, notes
  ) VALUES (
    'OASIS-' || to_char(p_appointment_date, 'YYYY') || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8)),
    auth.uid(), btrim(p_customer_name), btrim(p_customer_phone), btrim(p_customer_email), v_staff_id,
    p_appointment_date, p_start_time, p_start_time + make_interval(mins => v_duration),
    v_duration, v_price, 'confirmed', NULLIF(btrim(p_notes), '')
  ) RETURNING * INTO v_appointment;
  INSERT INTO public.appointment_services(appointment_id, service_id, service_name, service_price, duration_minutes)
    SELECT v_appointment.id, s.id, s.name, s.price, s.duration_minutes
      FROM public.services s WHERE s.id = ANY(p_service_ids);
  GET DIAGNOSTICS v_snapshot_count = ROW_COUNT;
  IF v_snapshot_count <> cardinality(p_service_ids) THEN
    RAISE EXCEPTION 'Could not snapshot every selected service';
  END IF;
  RETURN v_appointment;
END;
$$;

CREATE FUNCTION public.cancel_customer_booking(p_appointment_id uuid, p_reason text DEFAULT NULL)
RETURNS public.appointments LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_appointment public.appointments%ROWTYPE;
BEGIN
  SELECT * INTO v_appointment FROM public.appointments a
   WHERE a.id = p_appointment_id AND a.customer_id = auth.uid();
  IF NOT FOUND THEN RAISE EXCEPTION 'Appointment not found'; END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('oasis-booking-day:' || v_appointment.appointment_date::text, 0));
  SELECT * INTO v_appointment FROM public.appointments a
   WHERE a.id = p_appointment_id AND a.customer_id = auth.uid() FOR UPDATE;
  IF v_appointment.status IN ('cancelled', 'completed', 'no_show')
     OR v_appointment.appointment_date + v_appointment.start_time <= (now() AT TIME ZONE 'Asia/Kolkata') THEN
    RAISE EXCEPTION 'This appointment can no longer be cancelled';
  END IF;
  IF length(COALESCE(p_reason, '')) > 500 THEN RAISE EXCEPTION 'Cancellation reason is too long'; END IF;
  UPDATE public.appointments SET status = 'cancelled',
    notes = concat_ws(E'\n', NULLIF(notes, ''), CASE WHEN NULLIF(btrim(p_reason), '') IS NULL THEN NULL ELSE 'Cancellation reason: ' || btrim(p_reason) END),
    updated_at = now()
   WHERE id = p_appointment_id RETURNING * INTO v_appointment;
  RETURN v_appointment;
END;
$$;

CREATE FUNCTION public.reschedule_customer_booking(p_appointment_id uuid, p_new_date date, p_new_start time)
RETURNS public.appointments LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE
  v_appointment public.appointments%ROWTYPE;
  v_old_date date;
  v_staff_id uuid;
  v_service_ids uuid[];
BEGIN
  SELECT a.appointment_date INTO v_old_date FROM public.appointments a
   WHERE a.id = p_appointment_id AND a.customer_id = auth.uid();
  IF NOT FOUND THEN RAISE EXCEPTION 'Appointment not found'; END IF;
  IF v_old_date <= p_new_date THEN
    PERFORM pg_advisory_xact_lock(hashtextextended('oasis-booking-day:' || v_old_date::text, 0));
    IF p_new_date <> v_old_date THEN
      PERFORM pg_advisory_xact_lock(hashtextextended('oasis-booking-day:' || p_new_date::text, 0));
    END IF;
  ELSE
    PERFORM pg_advisory_xact_lock(hashtextextended('oasis-booking-day:' || p_new_date::text, 0));
    PERFORM pg_advisory_xact_lock(hashtextextended('oasis-booking-day:' || v_old_date::text, 0));
  END IF;
  SELECT * INTO v_appointment FROM public.appointments a
   WHERE a.id = p_appointment_id AND a.customer_id = auth.uid() FOR UPDATE;
  IF v_appointment.status IN ('cancelled', 'completed', 'no_show')
     OR v_appointment.appointment_date + v_appointment.start_time <= (now() AT TIME ZONE 'Asia/Kolkata') THEN
    RAISE EXCEPTION 'This appointment can no longer be rescheduled';
  END IF;
  SELECT array_agg(service_id ORDER BY service_id) INTO v_service_ids
    FROM public.appointment_services WHERE appointment_id = v_appointment.id;
  IF v_service_ids IS NULL OR cardinality(v_service_ids) = 0 THEN
    RAISE EXCEPTION 'This appointment has no service lines and cannot be safely rescheduled';
  END IF;
  v_staff_id := public.validate_booking_slot(
    p_new_date, p_new_start, v_appointment.total_duration_minutes, v_appointment.staff_id,
    v_service_ids, v_appointment.id
  );
  UPDATE public.appointments SET staff_id = v_staff_id, appointment_date = p_new_date,
    start_time = p_new_start, end_time = p_new_start + make_interval(mins => total_duration_minutes),
    status = 'confirmed', updated_at = now()
   WHERE id = p_appointment_id RETURNING * INTO v_appointment;
  RETURN v_appointment;
END;
$$;

CREATE FUNCTION public.update_appointment_status(p_appointment_id uuid, p_status public.appointment_status)
RETURNS public.appointments LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_appointment public.appointments%ROWTYPE; v_role public.user_role;
BEGIN
  v_role := public.current_user_role();
  IF v_role IS DISTINCT FROM 'staff' AND v_role IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Staff or administrator role required';
  END IF;
  SELECT * INTO v_appointment FROM public.appointments a WHERE a.id = p_appointment_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Appointment not found'; END IF;
  IF v_role = 'staff' THEN
    IF NOT public.is_assigned_staff(v_appointment.staff_id) THEN RAISE EXCEPTION 'Assigned staff access required'; END IF;
    IF NOT ((v_appointment.status = 'confirmed' AND p_status IN ('checked_in', 'in_progress'))
         OR (v_appointment.status = 'checked_in' AND p_status IN ('in_progress', 'completed'))
         OR (v_appointment.status = 'in_progress' AND p_status = 'completed')) THEN
      RAISE EXCEPTION 'Invalid staff appointment status transition';
    END IF;
  ELSIF v_role IS DISTINCT FROM 'admin' THEN RAISE EXCEPTION 'Staff or administrator role required';
  END IF;
  UPDATE public.appointments SET status = p_status, updated_at = now()
   WHERE id = p_appointment_id RETURNING * INTO v_appointment;
  RETURN v_appointment;
END;
$$;

CREATE FUNCTION public.record_appointment_payment(
  p_appointment_id uuid, p_method public.payment_method, p_upi_transaction_id text DEFAULT NULL, p_notes text DEFAULT NULL
) RETURNS public.payments LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_appointment public.appointments%ROWTYPE; v_payment public.payments%ROWTYPE;
BEGIN
  IF public.is_admin() IS DISTINCT FROM true THEN RAISE EXCEPTION 'Administrator role required'; END IF;
  SELECT * INTO v_appointment FROM public.appointments a WHERE a.id = p_appointment_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Appointment not found'; END IF;
  IF v_appointment.status IN ('cancelled', 'no_show') OR v_appointment.payment_status = 'completed' THEN
    RAISE EXCEPTION 'This appointment cannot receive another payment';
  END IF;
  INSERT INTO public.payments(appointment_id, booking_reference, customer_name, amount,
    payment_method, payment_status, upi_transaction_id, recorded_by, notes)
  VALUES (v_appointment.id, v_appointment.booking_reference, v_appointment.customer_name,
    v_appointment.total_price, p_method, 'completed', NULLIF(btrim(p_upi_transaction_id), ''), auth.uid(),
    NULLIF(btrim(p_notes), '')) RETURNING * INTO v_payment;
  UPDATE public.appointments SET payment_status = 'completed', payment_method = p_method, updated_at = now()
   WHERE id = v_appointment.id;
  RETURN v_payment;
END;
$$;

