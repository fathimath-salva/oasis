-- FRESH-DATABASE BASELINE ONLY. This is not an upgrade migration for an
-- existing hosted schema. Create operations are intentionally non-idempotent;
-- review and run only against a disposable empty local Supabase database first.
-- This migration intentionally does not import browser data.
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TYPE public.user_role AS ENUM ('customer', 'staff', 'admin');
CREATE TYPE public.gender_classification AS ENUM ('men', 'women', 'unisex');
CREATE TYPE public.appointment_status AS ENUM (
  'pending', 'confirmed', 'checked_in', 'in_progress', 'completed', 'cancelled', 'no_show'
);
CREATE TYPE public.payment_method AS ENUM ('cash', 'upi', 'card', 'online');
CREATE TYPE public.payment_status AS ENUM ('pending', 'completed', 'failed', 'refunded');

CREATE TABLE public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text NOT NULL,
  email text NOT NULL UNIQUE,
  phone text NOT NULL DEFAULT '',
  role public.user_role NOT NULL DEFAULT 'customer',
  avatar_url text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX profiles_phone_idx ON public.profiles(phone);
CREATE INDEX profiles_role_idx ON public.profiles(role);

CREATE TABLE public.services (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  category text NOT NULL,
  gender public.gender_classification NOT NULL DEFAULT 'unisex',
  description text NOT NULL DEFAULT '',
  price numeric(10,2) NOT NULL CHECK (price >= 0),
  price_confirmed boolean NOT NULL DEFAULT false,
  requires_confirmation boolean NOT NULL DEFAULT false,
  duration_minutes integer NOT NULL CHECK (duration_minutes BETWEEN 1 AND 600),
  is_active boolean NOT NULL DEFAULT true,
  image_url text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX services_category_idx ON public.services(category);
CREATE INDEX services_gender_idx ON public.services(gender);
CREATE INDEX services_active_idx ON public.services(is_active);

-- Contact details are stored separately so the public staff directory cannot
-- disclose staff phone numbers or email addresses.
CREATE TABLE public.staff (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  profile_id uuid UNIQUE REFERENCES public.profiles(id) ON DELETE SET NULL,
  name text NOT NULL,
  title text NOT NULL,
  specialties text[] NOT NULL DEFAULT '{}',
  is_active boolean NOT NULL DEFAULT true,
  rating numeric(3,2) NOT NULL DEFAULT 5.00 CHECK (rating BETWEEN 0 AND 5),
  avatar_url text,
  working_days integer[] NOT NULL DEFAULT '{0,1,2,3,4,5,6}',
  start_time time NOT NULL DEFAULT '09:00',
  end_time time NOT NULL DEFAULT '20:30',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (start_time < end_time),
  CHECK (working_days <@ ARRAY[0,1,2,3,4,5,6]::integer[])
);
CREATE TABLE public.staff_private (
  staff_id uuid PRIMARY KEY REFERENCES public.staff(id) ON DELETE CASCADE,
  phone text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT ''
);
CREATE TABLE public.staff_services (
  staff_id uuid NOT NULL REFERENCES public.staff(id) ON DELETE CASCADE,
  service_id uuid NOT NULL REFERENCES public.services(id) ON DELETE CASCADE,
  PRIMARY KEY (staff_id, service_id)
);
CREATE INDEX staff_services_service_idx ON public.staff_services(service_id);

CREATE TABLE public.salon_business_hours (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day_of_week integer NOT NULL UNIQUE CHECK (day_of_week BETWEEN 0 AND 6),
  day_name text NOT NULL,
  is_open boolean NOT NULL DEFAULT true,
  open_time time NOT NULL DEFAULT '09:00',
  close_time time NOT NULL DEFAULT '20:30',
  CHECK (NOT is_open OR open_time < close_time)
);
CREATE TABLE public.salon_holidays (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  holiday_date date NOT NULL UNIQUE,
  title text NOT NULL,
  description text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.appointments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_reference text NOT NULL UNIQUE,
  customer_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  customer_name text NOT NULL,
  customer_phone text NOT NULL,
  customer_email text NOT NULL,
  staff_id uuid NOT NULL REFERENCES public.staff(id) ON DELETE RESTRICT,
  appointment_date date NOT NULL,
  start_time time NOT NULL,
  end_time time NOT NULL,
  total_duration_minutes integer NOT NULL CHECK (total_duration_minutes > 0),
  total_price numeric(10,2) NOT NULL CHECK (total_price >= 0),
  status public.appointment_status NOT NULL DEFAULT 'pending',
  notes text,
  payment_status public.payment_status NOT NULL DEFAULT 'pending',
  payment_method public.payment_method,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (end_time > start_time)
);
CREATE INDEX appointments_date_idx ON public.appointments(appointment_date);
CREATE INDEX appointments_staff_idx ON public.appointments(staff_id);
CREATE INDEX appointments_status_idx ON public.appointments(status);
CREATE INDEX appointments_customer_idx ON public.appointments(customer_id);
-- Final database-level backstop. API writes also take an advisory lock so
-- "any available staff" allocation is serialized for the appointment date.
ALTER TABLE public.appointments ADD CONSTRAINT appointments_staff_no_overlap
  EXCLUDE USING gist (
    staff_id WITH =,
    tsrange(appointment_date + start_time, appointment_date + end_time, '[)') WITH &&
  ) WHERE (status NOT IN ('cancelled', 'no_show'));

CREATE TABLE public.appointment_services (
  appointment_id uuid NOT NULL REFERENCES public.appointments(id) ON DELETE CASCADE,
  service_id uuid NOT NULL REFERENCES public.services(id) ON DELETE RESTRICT,
  service_name text NOT NULL,
  service_price numeric(10,2) NOT NULL CHECK (service_price >= 0),
  duration_minutes integer NOT NULL CHECK (duration_minutes > 0),
  PRIMARY KEY (appointment_id, service_id)
);
CREATE INDEX appointment_services_service_idx ON public.appointment_services(service_id);

CREATE TABLE public.payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  appointment_id uuid NOT NULL UNIQUE REFERENCES public.appointments(id) ON DELETE RESTRICT,
  booking_reference text NOT NULL,
  customer_name text NOT NULL,
  amount numeric(10,2) NOT NULL CHECK (amount >= 0),
  payment_method public.payment_method NOT NULL,
  payment_status public.payment_status NOT NULL DEFAULT 'completed',
  upi_transaction_id text,
  recorded_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  notes text
);
CREATE INDEX payments_date_idx ON public.payments(recorded_at DESC);
CREATE TABLE public.audit_logs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  user_name text NOT NULL,
  user_role public.user_role NOT NULL,
  action text NOT NULL,
  entity_type text NOT NULL,
  entity_id text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
